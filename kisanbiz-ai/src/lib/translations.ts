export type TranslationKey = keyof (typeof translations)['English'];

export function getTranslation(lang: Language, key: TranslationKey): string {
  const currentLangDict = translations[lang] || translations['English'];
  return currentLangDict[key] || translations['English'][key] || key;
}

// Function to activate Google Translate on the live DOM
export function applyGoogleTranslate(lang: Language) {
  const langCode = lang === 'Hindi' ? 'hi' : lang === 'Marathi' ? 'mr' : 'en';

  // Set Google Translate cookie
  try {
    const cookieVal = `/en/${langCode}`;
    document.cookie = `googtrans=${cookieVal}; path=/;`;
    if (typeof window !== 'undefined' && window.location.hostname) {
      document.cookie = `googtrans=${cookieVal}; domain=${window.location.hostname}; path=/;`;
    }
  } catch (e) {
    console.warn('Could not set googtrans cookie', e);
  }

  // Trigger Google Translate combo dropdown if available
  const triggerCombo = () => {
    const select = document.querySelector('.goog-te-combo') as HTMLSelectElement | null;
    if (select) {
      select.value = langCode;
      select.dispatchEvent(new Event('change'));
      return true;
    }
    return false;
  };

  if (!triggerCombo()) {
    // If not found yet, ensure Google Translate script is loaded
    if (typeof window !== 'undefined' && !(window as any).google?.translate) {
      const existingScript = document.getElementById('google-translate-script');
      if (!existingScript) {
        (window as any).googleTranslateElementInit = () => {
          try {
            new (window as any).google.translate.TranslateElement(
              {
                pageLanguage: 'en',
                includedLanguages: 'en,hi,mr',
                autoDisplay: false,
              },
              'google_translate_element'
            );
            setTimeout(triggerCombo, 300);
          } catch (err) {
            console.warn('Google Translate initialization warning:', err);
          }
        };

        const script = document.createElement('script');
        script.id = 'google-translate-script';
        script.src = 'https://translate.google.com/translate_a/element.js?cb=googleTranslateElementInit';
        script.async = true;
        document.body.appendChild(script);
      }
    } else {
      setTimeout(triggerCombo, 300);
    }
  }
}
